#!/usr/bin/env python3
"""Write docs/vX.Y.Z-verification.md with the evidence of the gate.

release.sh records every gate command and its exit code in a record file
(one `<exit code><TAB><command>` line per command) and keeps the gate's
output in a log. This tool turns them into the verification report:

  - the date, commit, tag and the CI workflows that were polled;
  - "Gate commands:" and "Exit codes:", numbered the same, one per command
    that ran (the artifact freshness checks, then the gate);
  - the SHA-256 of the gate log, so that the log kept by the operator can be
    shown to be the one this report describes.

The report's own SHA-256 goes into a sibling file, `<report>.sha256`, in the
format `sha256sum -c` reads (run it from the repository root). It cannot sit
in the report, because the hash would change the report.

The tool records what happened; it does not judge. A non-zero exit code in
the record is written as it is and the Result line says FAIL.

Exit codes: 0 = written; 2 = no evidence to record (record missing/empty).
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_record(path: Path) -> list[tuple[int, str]]:
    rows: list[tuple[int, str]] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip():
            continue
        code, _, cmd = raw.partition("\t")
        if not cmd or not code.strip().lstrip("-").isdigit():
            raise ValueError(f"malformed record line: {raw!r}")
        rows.append((int(code), cmd))
    return rows


def render(version: str, commit: str, tag: str, date: str, workflows: str,
           rows: list[tuple[int, str]], log_sha: str, log_path: str) -> str:
    failed = [r for r in rows if r[0] != 0]
    result = (f"PASS: all {len(rows)} commands exited 0" if not failed
              else f"FAIL: {len(failed)} of {len(rows)} commands exited non-zero")
    out = [
        f"# v{version} verification",
        "",
        f"Date: {date}",
        f"Commit: {commit}",
        f"Tag: {tag}",
        "",
        "## What changed",
        "",
        f"See the release notes for v{version} at",
        f"https://github.com/slimissa/iso3166/releases/tag/v{version}",
        "",
        "## CI at the tag",
        "",
        f"Workflows: {workflows}",
        "The release commit's CI completed green before the tag was pushed.",
        "",
        "## Gate evidence",
        "",
        f"Result: {result}",
        f"Gate log SHA-256: {log_sha}",
        "",
        f"The gate log is `{log_path}` on the machine that ran the",
        "release. It is not committed; keep it, and compare its SHA-256 with",
        "the line above. The report's own SHA-256 is in the sibling file",
        f"`docs/v{version}-verification.md.sha256`.",
        "",
        "Gate commands:",
        "",
    ]
    out += [f"{i:>3}. {cmd}" for i, (_, cmd) in enumerate(rows, 1)]
    out += ["", "Exit codes:", ""]
    out += [f"{i:>3}. {code}" for i, (code, _) in enumerate(rows, 1)]
    out += [
        "",
        "## Notes",
        "",
        "This report is generated by `scripts/release.sh` through",
        "`tools/write_verification_report.py`. Edit by hand if additional",
        "context is needed; the `.sha256` file will then no longer match,",
        "which is the point of it.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--version", required=True)
    p.add_argument("--commit", required=True)
    p.add_argument("--tag", required=True)
    p.add_argument("--date", required=True)
    p.add_argument("--workflows", required=True)
    p.add_argument("--gate-rec", type=Path, required=True,
                   help="Record file: '<exit code>\\t<command>' per line.")
    p.add_argument("--gate-log", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args(argv)

    try:
        rows = read_record(a.gate_rec)
    except (OSError, ValueError) as exc:
        print(f"write_verification_report: cannot read the gate record: {exc}",
              file=sys.stderr)
        return 2
    if not rows:
        print("write_verification_report: the gate record is empty; refusing "
              "to write a report with no evidence", file=sys.stderr)
        return 2
    if not a.gate_log.is_file():
        print(f"write_verification_report: gate log not found: {a.gate_log}",
              file=sys.stderr)
        return 2

    report = render(a.version, a.commit, a.tag, a.date, a.workflows, rows,
                    sha256_file(a.gate_log), str(a.gate_log))
    a.out.write_text(report, encoding="utf-8")
    sidecar = a.out.with_name(a.out.name + ".sha256")
    sidecar.write_text(f"{sha256_file(a.out)}  {a.out.as_posix()}\n",
                       encoding="utf-8")
    print(f"wrote {a.out} ({len(rows)} commands) and {sidecar.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
